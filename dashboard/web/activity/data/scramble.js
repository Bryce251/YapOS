export const TIERS = Object.freeze([
  Object.freeze({ id: 'short', name: 'Short', emoji: '🌱', hint: '4 to 5 letters', min: 4, max: 5 }),
  Object.freeze({ id: 'medium', name: 'Medium', emoji: '🌿', hint: '6 to 7 letters', min: 6, max: 7 }),
  Object.freeze({ id: 'long', name: 'Long', emoji: '🌳', hint: '8 to 9 letters', min: 8, max: 9 }),
]);

export const WORDS = Object.freeze(SHORT.concat(MEDIUM, LONG));

export function wordById(id) {
  return Number.isInteger(id) && id >= 0 && id < WORDS.length ? WORDS[id] : null;
}

export function tierOf(word) {
  const n = String(word || '').length;
  const t = TIERS.find((x) => n >= x.min && n <= x.max);
  return t ? t.id : null;
}

export function idsIn(tier) {
  const out = [];
  WORDS.forEach((w, i) => {
    if (tierOf(w) === tier) out.push(i);
  });
  return out;
}
