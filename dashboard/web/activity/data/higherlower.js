let seq = 0;
export const ITEMS = Object.freeze(
  Object.entries(ROWS).flatMap(([kind, rows]) =>
    rows.map(([emoji, name, value]) => {
      seq += 1;
      return Object.freeze({ id: `hl${String(seq).padStart(3, '0')}`, kind, emoji, name, value });
    }),
  ),
);

const BY_ID = new Map(ITEMS.map((x) => [x.id, x]));

export function itemById(id) {
  return BY_ID.get(id) || null;
}

function sig(n, digits = 3) {
  if (!Number.isFinite(n) || n === 0) return 0;
  const p = Math.pow(10, Math.floor(Math.log10(Math.abs(n))) + 1 - digits);
  return Math.round(n / p) * p;
}

function num(n) {
  if (Math.abs(n) >= 1000) return Math.round(n).toLocaleString('en-US');
  if (Math.abs(n) >= 10) return String(Math.round(n));
  return String(Math.round(n * 10) / 10);
}

function people(n) {
  if (n >= 1e9) return `${(Math.round(n / 1e7) / 100).toString()} billion people`;
  if (n >= 1e6) return `${num(Math.round(n / 1e5) / 10)} million people`;
  return `${num(sig(n, 2))} people`;
}

export function showValue(item) {
  if (!item) return '';
  const k = KINDS[item.kind];
  if (!k) return String(item.value);
  const lead = k.about ? 'about ' : '';
  if (item.kind === 'year') return String(item.value);
  if (item.kind === 'people') return `${lead}${people(item.value)}`;
  if (item.kind === 'food') return `${lead}${num(item.value)} kcal`;
  const main = `${num(item.kind === 'area' ? sig(item.value, 3) : item.value)} ${k.unit}`;
  if (!k.us) return `${lead}${main}`;
  const other = item.value * k.rate;
  return `${lead}${main} (${num(k.about ? sig(other, other >= 100 ? 3 : 2) : other)} ${k.us})`;
}
