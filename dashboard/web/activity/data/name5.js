function slug(name) {
  return name
    .toLowerCase()
    .replace(/[’']/g, '')
    .replace(/\([^)]*\)/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export const CATEGORIES = Object.freeze(ROWS.map(([emoji, name]) => Object.freeze({ id: slug(name), name, emoji })));

export const EASY_LETTERS = Object.freeze('ABCDEFGHIJKLMNOPRSTW'.split(''));
export const HARD_LETTERS = Object.freeze('QUVXYZ'.split(''));

const BY_ID = new Map(CATEGORIES.map((c) => [c.id, c]));

export function categoryById(id) {
  return BY_ID.get(id) || null;
}
